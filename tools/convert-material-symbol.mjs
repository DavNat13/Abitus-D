// Converts Material Symbols Outlined SVGs (viewBox "0 -960 960 960", 24 px, weight 400)
// into Android vector drawables named ic_<name>.xml (05b-UI-TOKENS.md, Iconografia).
// Usage: node tools/convert-material-symbol.mjs <svg-dir> <android-res-drawable-dir>
// Source: github.com/google/material-design-icons/tree/master/symbols/web (Apache 2.0).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const [sourceDir, targetDir] = process.argv.slice(2);
if (!sourceDir || !targetDir) {
  console.error('usage: node tools/convert-material-symbol.mjs <svg-dir> <drawable-dir>');
  process.exit(1);
}

function toVector(svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1]?.split(/\s+/).map(Number);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (!viewBox || viewBox.length !== 4 || paths.length === 0) throw new Error('unsupported svg');
  const [minX, minY, width, height] = viewBox;
  const body = paths
    .map((d) => `        <path\n            android:fillColor="@android:color/white"\n            android:pathData="${d}" />`)
    .join('\n');
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by tools/convert-material-symbol.mjs from Material Symbols Outlined (Apache 2.0). -->',
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '    android:width="24dp"',
    '    android:height="24dp"',
    `    android:viewportWidth="${width}"`,
    `    android:viewportHeight="${height}">`,
    `    <group android:translateX="${-minX}" android:translateY="${-minY}">`,
    body,
    '    </group>',
    '</vector>',
    '',
  ].join('\n');
}

for (const file of (await readdir(sourceDir)).filter((name) => name.endsWith('.svg'))) {
  const name = path.basename(file, '.svg').replace(/_24px$/, '');
  const xml = toVector(await readFile(path.join(sourceDir, file), 'utf8'));
  await writeFile(path.join(targetDir, `ic_${name}.xml`), xml);
  console.log(`ic_${name}.xml`);
}
