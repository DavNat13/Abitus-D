import { mkdir, writeFile } from 'node:fs/promises';

// Generated resources only. Upstream paths are preserved; grouping is Abitus-D's adaptation.
const revision = '15c8085ee97cb94c51f92c75224416b15f955b5c';
const base = `https://raw.githubusercontent.com/vulovix/body-muscles/${revision}`;
async function source(path) {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) throw new Error(`${path}: ${response.status}`);
  return response.text();
}
const license = await source('LICENSE');
const notice = await source('NOTICE');
if (!license.includes('Apache License') || !notice.includes('Copyright 2024 Ivan Vulović')) {
  throw new Error('Upstream license or notice changed');
}
const output = 'android/app/src/main/res/raw';
await mkdir(output, { recursive: true });
// Reflow paragraphs, retaining the entire license text, to respect the file-length rule.
await writeFile(`${output}/body_muscles_license.txt`, license.trim().split(/\n\s*\n/)
  .map(p => p.trim().replace(/\s*\n\s*/g, ' ')).join('\n\n') + '\n');
await writeFile(`${output}/body_muscles_notice.txt`, notice);
const groups = [
  [/^shoulder-front-/, 'deltoid_anterior'], [/^shoulder-side-/, 'deltoid_lateral'],
  [/^deltoid-rear-/, 'deltoid_posterior'], [/^chest-/, 'chest'],
  [/^biceps-/, 'biceps'], [/^triceps-/, 'triceps'],
  [/^forearm-extensors-/, 'forearm_extensors'], [/^forearm-/, 'forearm_flexors'],
  [/^abs-/, 'abdominals'], [/^obliques-/, 'obliques'],
  [/^quads-/, 'quadriceps'], [/^adductors-/, 'adductors'],
  [/^tibialis-anterior-/, 'tibialis_anterior'], [/^traps-upper-/, 'traps_upper'],
  [/^traps-(mid|lower)-/, 'traps_middle_lower'], [/^lats-/, 'lats'],
  [/^lower-back-/, 'lower_back'], [/^gluteus-/, 'glutes'],
  [/^hamstrings-/, 'hamstrings'], [/^calves-/, 'calves'],
];
for (const side of ['front', 'back']) {
  const text = await source(`src/data/muscles.${side}.ts`);
  const regions = [...text.matchAll(/id: "([^"]+)"[\s\S]*?path: "([^"]+)"/g)];
  if (regions.length < 30) throw new Error(`Incomplete ${side} data`);
  const entries = regions.map(([, id, path]) => {
    const group = groups.find(([pattern]) => pattern.test(id));
    const key = group ? `svg_${group[1]}` : '';
    return `    <region id="${id}" key="${key}" path="${path}" />`;
  });
  await writeFile(`${output}/body_muscles_${side}.xml`, [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by tools/import-body-muscles.mjs; do not edit paths manually.',
    'Copyright 2024 Ivan Vulović. Apache-2.0. See body_muscles_license.txt and body_muscles_notice.txt.',
    `Source: vulovix/body-muscles @ ${revision}.`,
    'Modified by Abitus-D: XML conversion and catalog grouping. -->',
    '<body>', ...entries, '</body>', '',
  ].join('\n'));
  console.log(`${side}: ${regions.length} regions`);
}
